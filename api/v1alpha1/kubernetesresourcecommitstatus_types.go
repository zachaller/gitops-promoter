// KubernetesResourceCommitStatus is the Schema for the kubernetesresourcecommitstatuses API.
//
// It gates promotions on a Kubernetes resource the controller creates from a wrapped template, for example a
// batch/v1 Job that runs a smoke test, and reports the phase computed from that resource's live status.
